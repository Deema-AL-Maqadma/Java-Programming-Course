package assigment1;

public class Square3 {
    
private double sideLength;

public Square3(){
    sideLength=0.0;
}
public Square3(double s){
    sideLength= s;
}
public double getArea()
{
return sideLength * sideLength;
}
public double getSideLength()
{
return sideLength;
}
    
}
